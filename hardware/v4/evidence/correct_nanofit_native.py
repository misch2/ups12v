"""Native KiCad 10 library correction; never authors serialized CAD text."""
from pathlib import Path
import hashlib, json
import pcbnew
from verify_nanofit import parse, many, one

E = Path(__file__).resolve().parent
L = E.parent / 'ups_v4/ups_v4.pretty'
SOURCE = Path('C:/Program Files/KiCad/10.0/share/kicad/footprints/Connector_Molex.pretty')
BASE = E / 'nanofit-native-stock.pretty'
BASE.mkdir(exist_ok=True)

def pad_info(p):
    return {'number':p.GetNumber(), 'position_nm':[p.GetPosition().x,p.GetPosition().y],
            'size_nm':[p.GetSize().x,p.GetSize().y], 'drill_nm':[p.GetDrillSize().x,p.GetDrillSize().y],
            'drill_shape':p.GetDrillShape(), 'shape':p.GetShape(), 'attribute':p.GetAttribute(),
            'angle':p.GetOrientationDegrees(), 'layers':p.GetLayerSet().FmtHex(),
            'offset_nm':[p.GetOffset().x,p.GetOffset().y], 'round_ratio':p.GetRoundRectRadiusRatio()}

def normalized(n):
    # UUIDs are regenerated by native load, so compare every other serialized attribute.
    if isinstance(n,list):
        return [normalized(x) for x in n if not (isinstance(x,list) and x and x[0]=='uuid')]
    return n

results=[]
assert pcbnew.GetBuildVersion().startswith('10.')
for count in (2,3):
    name=f'Molex_Nano-Fit_105313-xx0{count}_1x0{count}_P2.50mm_Horizontal'
    target=name+'_RevJ1'
    f=pcbnew.FootprintLoad(str(SOURCE),name)
    assert f is not None
    # Empty evidence library cannot be auto-detected by the wrapper; select native plugin explicitly.
    pcbnew.PCB_IO_MGR.FindPlugin(pcbnew.PCB_IO_MGR.KICAD_SEXP).FootprintSave(str(BASE),f)
    before=[pad_info(p) for p in f.Pads()]
    numbered=[x for x in before if x['number']]
    assert len(numbered)==count
    mechanical=[p for p in f.Pads() if not p.GetNumber()]
    assert len(mechanical)==2
    for p in mechanical:
        x,y=p.GetPosition().x,p.GetPosition().y
        assert x==7180000 and y in (0,(count-1)*2500000)
        assert p.GetAttribute()==pcbnew.PAD_ATTRIB_NPTH and p.GetOrientationDegrees()==0
        slot=y==0
        p.SetDrillShape(pcbnew.PAD_DRILL_SHAPE_OBLONG if slot else pcbnew.PAD_DRILL_SHAPE_CIRCLE)
        p.SetDrillSize(pcbnew.VECTOR2I(1600000,1750000 if slot else 1600000))
        p.SetSize(pcbnew.VECTOR2I(1600000,1750000 if slot else 1600000))
        p.SetShape(pcbnew.PAD_SHAPE_OVAL if slot else pcbnew.PAD_SHAPE_CIRCLE)
    assert [pad_info(p) for p in f.Pads() if p.GetNumber()]==numbered
    f.SetFPIDAsString('ups_v4:'+target)
    if not (L/(target+'.kicad_mod')).exists():
        pcbnew.FootprintSave(str(L),f)
    r=pcbnew.FootprintLoad(str(L),target)
    assert r is not None
    after=[pad_info(p) for p in r.Pads()]
    assert [x for x in after if x['number']]==numbered
    for p in r.Pads():
        if not p.GetNumber():
            assert p.GetDrillShape()==(pcbnew.PAD_DRILL_SHAPE_OBLONG if p.GetPosition().y==0 else pcbnew.PAD_DRILL_SHAPE_CIRCLE)
            assert p.GetDrillSize().x==1600000
            assert p.GetDrillSize().y==(1750000 if p.GetPosition().y==0 else 1600000)
            assert p.GetOrientationDegrees()==0
    original=normalized(parse((BASE/(name+'.kicad_mod')).read_text(encoding='utf-8')))
    corrected=normalized(parse((L/(target+'.kicad_mod')).read_text(encoding='utf-8')))
    original[1]=corrected[1] # identity is intentionally different
    oldpads=many(original,'pad'); newpads=many(corrected,'pad')
    assert len(oldpads)==len(newpads)
    for a,b in zip(oldpads,newpads):
        if a[1]=='':
            assert b[1]==''
            # Only these three NPTH geometry clauses may change.
            a[3]=b[3]
            for key in ('size','drill'):
                a[a.index(one(a,key))]=one(b,key)
            # Native writer emits the existing default 45-degree spoke angle for oval pads.
            # NPTH has no thermal connection; assert unchanged effective angle before normalizing.
            if one(a,'thermal_bridge_angle') is None and one(b,'thermal_bridge_angle') is not None:
                assert one(b,'thermal_bridge_angle')==['thermal_bridge_angle','45']
                b.remove(one(b,'thermal_bridge_angle'))
    assert original==corrected, 'Unexpected non-mechanical change in native saved footprint'
    results.append({'name':target,'before':before,'after':after,'electrical_identical':True,
                    'all_other_serialized_attributes_identical_except_identity_and_UUID':True,
                    'sha256':hashlib.sha256((L/(target+'.kicad_mod')).read_bytes()).hexdigest()})
(E/'nanofit-native-correction.json').write_text(json.dumps({'kicad':pcbnew.GetBuildVersion(),
    'drawing':'SD-105313-100 Rev J1, sheet 1, connector-side view; independently rendered 2026-10-11',
    'pdf_sha256':hashlib.sha256((E/'nanofit-revj1.pdf').read_bytes()).hexdigest(),'footprints':results},indent=2)+'\n')
print('PASS: two native save/reload corrections; all electrical pads and non-mechanical attributes preserved')
